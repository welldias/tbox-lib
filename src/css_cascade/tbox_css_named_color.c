static const size_t tbox_css_named_color_count = sizeof(tbox_css_named_colors) / sizeof(tbox_css_named_colors[0]);

static bool tbox_css_rgb_equal(tbox_css_rgba x, tbox_css_rgba y) {
    return x.r == y.r && x.g == y.g && x.b == y.b && x.a == y.a;
}

bool tbox_css_named_color_find(tbox_string_view name, tbox_css_rgba *out_color) {
    if (name.data == NULL) {
        return false;
    }
    for (size_t i = 0; i < tbox_css_named_color_count; i++) {
        if (tbox_string_view_equal_ascii_ci(name, tbox_string_view_from_cstr(tbox_css_named_colors[i].name))) {
            if (out_color != NULL) {
                *out_color = tbox_css_named_colors[i].color;
            }
            return true;
        }
    }
    return false;
}

tbox_string_view tbox_css_named_color_name(tbox_css_rgba color) {
    for (size_t i = 0; i < tbox_css_named_color_count; i++) {
        if (tbox_css_rgb_equal(color, tbox_css_named_colors[i].color)) {
            return tbox_string_view_from_cstr(tbox_css_named_colors[i].name);
        }
    }
    return tbox_string_view_make(NULL, 0);
}
